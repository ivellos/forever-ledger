# Builds ClassicCrafts.lua: every craft of original Classic's professions (Alchemy,
# Blacksmithing, Cooking, Enchanting, Engineering, First Aid, Leatherworking, Tailoring,
# Mining's smelting), with the skill it needs, what it makes (and how many), what a vendor
# pays for that, and its materials. For the "All professions" view of Shuffles' Sells to a
# vendor tab (owner, November 12, 2026); recipes seen in the game's own profession windows
# (the recipe book) take precedence.
# Source (MIT licence):
#   wow-classic-items by nexus-devs  https://github.com/nexus-devs/wow-classic-items
# The data also has later expansions' crafts: only Classic's professions, skill up to 300,
# and Classic item numbers (under 25000, materials too) are kept.
# Run from the repo root:  powershell -File tools\build-classic-crafts.ps1
# (Uses the copy build-classic-data.ps1 downloads, if it's there.)

$ErrorActionPreference = "Stop"
$tmp = Join-Path $env:TEMP "fl-classic-data"
New-Item -ItemType Directory -Force $tmp | Out-Null
$file = Join-Path $tmp "items.json"
if (-not (Test-Path $file)) {
  Invoke-WebRequest "https://raw.githubusercontent.com/nexus-devs/wow-classic-items/master/data/json/data.json" -OutFile $file
}
$items = Get-Content $file -Raw -Encoding UTF8 | ConvertFrom-Json

$profs = @{ "Alchemy" = 1; "Blacksmithing" = 1; "Cooking" = 1; "Enchanting" = 1; "Engineering" = 1;
            "First Aid" = 1; "Leatherworking" = 1; "Tailoring" = 1; "Mining" = 1 }
$MAX_ID, $MAX_SKILL = 25000, 300

$rows = New-Object System.Collections.Generic.List[string]
$seen = @{}
foreach ($it in ($items | Sort-Object itemId)) {
  if ($it.itemId -ge $MAX_ID -or -not $it.createdBy) { continue }
  foreach ($c in $it.createdBy) {
    if (-not $profs[$c.category] -or $c.requiredSkill -gt $MAX_SKILL -or -not $c.reagents) { continue }
    $mats = @()
    $ok = $true
    foreach ($r in $c.reagents) {
      if ($r.itemId -ge $MAX_ID) { $ok = $false; break }
      $mats += ("{0}:{1}" -f $r.itemId, $r.amount)
    }
    if (-not $ok) { continue }
    $min, $max = 1, 1
    if ($c.amount) { $min, $max = $c.amount[0], $c.amount[-1] }
    $sell = 0
    if ($it.sellPrice) { $sell = [int]$it.sellPrice }
    $line = '  {{ "{0}", {1}, {2}, {3}, {4}, {5}, "{6}" }},' -f $c.category, $c.requiredSkill, $it.itemId, $min, $max, $sell, ($mats -join ",")
    if (-not $seen[$line]) { $seen[$line] = $true; $rows.Add($line) }
  }
}

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine("local _, ns = ...")
[void]$out.AppendLine("")
[void]$out.AppendLine("-- Original Classic crafts for Shuffles' ""All professions"" view, unconfirmed in Forever until a")
[void]$out.AppendLine("-- profession window shows them (the recipe book). Generated by tools/build-classic-crafts.ps1")
[void]$out.AppendLine("-- from wow-classic-items (nexus-devs), MIT licence. Don't edit by hand; rerun the script.")
[void]$out.AppendLine("--")
[void]$out.AppendLine("-- CLASSIC_CRAFTS = { { profession, skill needed, item made, made at least, made at most,")
[void]$out.AppendLine("--   what a vendor pays for one (copper, Classic's), ""material:count,..."" }, ... }")
[void]$out.AppendLine("ns.CLASSIC_CRAFTS = {")
foreach ($r in $rows) { [void]$out.AppendLine($r) }
[void]$out.AppendLine("}")
$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText((Join-Path (Get-Location) "ClassicCrafts.lua"), $out.ToString().Replace("`r`n", "`n"), $utf8)
"Wrote ClassicCrafts.lua: $($rows.Count) crafts"
